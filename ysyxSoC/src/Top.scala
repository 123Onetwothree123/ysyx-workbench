package ysyx

import chisel3._
import org.chipsalliance.cde.config.{Parameters, Config}
import freechips.rocketchip.system._
import freechips.rocketchip.diplomacy.LazyModule

object Config {
  // 这些 helper 只服务于“没有 NPC_CONFIG_JSON”的兼容路径。正常构建
  // 由 npc/Makefile 传入 typed JSON，下面的 env 值不会参与算术。
  private def legacyBool(name: String, default: Boolean): Boolean =
    sys.env.get(name).map(_.trim.toLowerCase).map {
      case "y" | "yes" | "true" | "1" => true
      case "n" | "no" | "false" | "0" | "" => false
      case other =>
        throw new IllegalArgumentException(
          s"$name 必须是 y/n，当前值 '$other'"
        )
    }.getOrElse(default)

  private def legacyInt(name: String, default: Int): Int =
    sys.env.get(name).map { raw =>
      try raw.trim.toInt
      catch {
        case _: NumberFormatException =>
          throw new IllegalArgumentException(
            s"$name 必须是整数，当前值 '$raw'"
          )
      }
    }.getOrElse(default)

  private def legacySocXlen: Int =
    legacyInt(
      "SOC_XLEN",
      legacyInt("CPU_XLEN", legacyInt("XLEN", 32))
    )

  // Keep this switch identical to the CPU PMA map generated by npc/Makefile.
  def hasChipLink: Boolean =
    SoCConfig.boolean("soc.chiplink", legacyBool("CHIPLINK", false))

  def sdramUseAXI: Boolean =
    SoCConfig.boolean("soc.sdram_use_axi", true)

  /** CPU 侧 AXI4 端口的 XLEN。
    *
    * 正常构建从 typed JSON 的 `soc.soc_xlen` 读取；该值已经由
    * npc/Makefile 根据 SOC_XLEN_FOLLOW_CPU 解析为最终有效值。
    * JSON 不存在时才回退到旧环境变量优先级：
    * SOC_XLEN > CPU_XLEN > XLEN > 32。
    */
  lazy val socXlen: Int = {
    val value = SoCConfig.int("soc.soc_xlen", legacySocXlen)
    require(
      value == 32 || value == 64,
      s"SOC_XLEN 必须是 32 或 64，当前值 $value"
    )
    value
  }

  /** SoC 内部互联/外设仍固定 32 位；SOC_XLEN 只改变 CPU 边界。 */
  def cpuAXI4AddrBits: Int = socXlen
  def cpuAXI4DataBits: Int = socXlen

  // APB/AXI 延迟模型的频率与缩放因子。它们现在属于 typed JSON 的
  // `soc.apb` / `soc.axi` 段，避免 ysyxSoC 和 NPC 各自读环境变量。
  def apbCpuFreqMhz: Int =
    SoCConfig.int("soc.apb.cpu_freq_mhz", legacyInt("APB_CPU_FREQ_MHZ", 450))
  def apbDeviceFreqMhz: Int =
    SoCConfig.int("soc.apb.device_freq_mhz", legacyInt("APB_DEVICE_FREQ_MHZ", 100))
  def apbDelayScale: Int =
    SoCConfig.int("soc.apb.delay_scale", legacyInt("APB_DELAY_SCALE_FACTOR", 64))
  def axiCpuFreqMhz: Int =
    SoCConfig.int("soc.axi.cpu_freq_mhz", legacyInt("AXI_CPU_FREQ_MHZ", 450))
  def axiDeviceFreqMhz: Int =
    SoCConfig.int("soc.axi.device_freq_mhz", legacyInt("AXI_DEVICE_FREQ_MHZ", 100))
  def axiDelayScale: Int =
    SoCConfig.int("soc.axi.delay_scale", legacyInt("AXI_DELAY_SCALE_FACTOR", 64))

  def source: String = SoCConfig.source
}

class ysyxSoCTop extends Module {
  // Edge32BitConfig 固定内部 TileLink/AXI 互联为 32 位。64 位 CPU
  // 构建仍使用 32 位内部总线，只是 CPU 端口经由 AXI4Downsizer 连接。
  private val rvConfig =
    if (Config.socXlen == 64) new Edge32BitConfig
    else new Edge32BitConfig ++ new DefaultRV32Config
  implicit val config: Parameters = new Config(rvConfig)

  val io = IO(new Bundle { })
  val dut = LazyModule(new ysyxSoCFull)
  val mdut = Module(dut.module)
  mdut.dontTouchPorts()
  mdut.externalPins := DontCare
  mdut.debug_gpr_raddr := 0.U
  // ysyxSoCTop 只是图形/Verilog 导出壳，不接仿真调试读口；
  // 真正的调试/DiffTest 顶层 ysyxSoCFull 由 npc 直接实例化。
  mdut.debug_fpr_raddr := 0.U
}

object Elaborate extends App {
  println(
    s"[ysyxSoC] config source: ${Config.source}; " +
      s"soc_xlen=${Config.socXlen}, chiplink=${Config.hasChipLink}, " +
      s"sdram_axi=${Config.sdramUseAXI}, " +
      s"apb=${Config.apbCpuFreqMhz}/${Config.apbDeviceFreqMhz}MHz/S=${Config.apbDelayScale}, " +
      s"axi=${Config.axiCpuFreqMhz}/${Config.axiDeviceFreqMhz}MHz/S=${Config.axiDelayScale}"
  )
  if (Config.socXlen == 64) {
    println(
      "[ysyxSoC] soc_xlen=64: CPU AXI4 is 64-bit. Debug/trap ports expose " +
        "the historical 32-bit low words plus `_hi` words, so RV64 " +
        "PC/GPR/CSR/trap state is observable without truncation."
    )
  }
  val firtoolOptions = Array("--disable-annotation-unknown")
  circt.stage.ChiselStage.emitSystemVerilogFile(new ysyxSoCTop, args, firtoolOptions)
}
