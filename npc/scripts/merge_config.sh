#!/usr/bin/env bash
# 从 profile 组合 Kconfig 片段并生成 .config。
#
# profile 每行一个片段路径（相对 npc/configs/，也允许绝对路径），
# '#' 开头为注释。片段按出现顺序拼接；c_conf 的 defconfig 读取器
# 按行应用，同名符号后出现的定义会覆盖前面的定义（可能打印
# "override" 警告，但最终值以最后一个片段为准）。
set -euo pipefail

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
npc_home=$(cd -- "$script_dir/.." && pwd)
configs_dir=$npc_home/configs
profiles_dir=$configs_dir/profiles
conf=$npc_home/tools/build/c_conf
kconfig=$npc_home/Kconfig
contract=$npc_home/tools/build/kconfig_contract
invocation_dir=$PWD

die() {
	printf 'merge_config: %s\n' "$*" >&2
	exit 1
}

usage() {
	cat >&2 <<'EOF'
用法: scripts/merge_config.sh PROFILE

PROFILE 可以是 configs/profiles/ 下的名称（可省略 .profile），也可以是
profile 文件路径。profile 中的片段路径相对 npc/configs/ 解析。

示例:
  scripts/merge_config.sh rv64_linux
  scripts/merge_config.sh rv64_linux_uboot_128m
  scripts/merge_config.sh configs/profiles/rv64_linux.profile
EOF
}

resolve_profile() {
	local arg=$1 candidate

	if [[ $arg == /* ]]; then
		[[ -f $arg ]] || die "profile 不存在: $arg"
		printf '%s\n' "$arg"
		return
	fi

	# 先按 configs/profiles/ 下的名称查找（允许带或不带 .profile）。
	if [[ $arg != */* ]]; then
		for candidate in "$profiles_dir/$arg.profile" "$profiles_dir/$arg"; do
			if [[ -f $candidate ]]; then
				printf '%s\n' "$candidate"
				return
			fi
		done
	fi

	# 再按调用目录和 npc/ 根目录解析显式路径。
	for candidate in "$invocation_dir/$arg" "$npc_home/$arg"; do
		if [[ -f $candidate ]]; then
			printf '%s\n' "$candidate"
			return
		fi
	done

	die "找不到 profile '$arg'（已查找 $profiles_dir/$arg.profile 和相对路径）"
}

[[ $# -eq 1 ]] || { usage; exit 2; }

profile=$(resolve_profile "$1")
profile=$(cd -- "$(dirname -- "$profile")" && pwd)/$(basename -- "$profile")

[[ -x $conf ]] || die "找不到 $conf；请先在 npc/ 下运行 make menuconfig 或 make profile-defconfig 构建 c_conf"
[[ -f $kconfig ]] || die "找不到 Kconfig: $kconfig"
[[ -x $contract ]] || die "找不到配置契约工具: $contract；请先在 npc/ 下运行 make kconfig-contract-tool 或 make profile-defconfig"

tmpdir=$(mktemp -d "${TMPDIR:-/tmp}/npc-merge-config.XXXXXX")
trap 'rm -rf -- "$tmpdir"' EXIT
merged=$tmpdir/merged.config

{
	printf '# Automatically generated by npc/scripts/merge_config.sh. DO NOT EDIT.\n'
	printf '# Profile: %s\n' "${profile#"$npc_home"/}"
	printf '# Fragments are concatenated in order; later symbols win.\n'
	echo

	while IFS= read -r raw || [[ -n $raw ]]; do
		line=${raw%$'\r'}
		# 去掉行首/行尾空白；只支持整行注释，不支持行尾注释。
		line="${line#"${line%%[![:space:]]*}"}"
		line="${line%"${line##*[![:space:]]}"}"
		[[ -z $line || $line == \#* ]] && continue

		if [[ $line == /* ]]; then
			fragment=$line
		else
			fragment=$configs_dir/$line
		fi
		[[ -f $fragment ]] || \
			die "profile '$profile' 引用的片段不存在: $line (解析为 $fragment)"

		printf '# ===== fragment: %s =====\n' "$line"
		cat -- "$fragment"
		echo
	done < "$profile"
} > "$merged"

grep -Eq '^CONFIG_|^# CONFIG_' "$merged" || \
	die "profile '$profile' 没有产生任何 CONFIG_ 行"

cd -- "$npc_home"
"$conf" -s --defconfig="$merged" "$kconfig"
"$conf" -s --syncconfig "$kconfig"
"$contract" --config .config

printf '已从 profile %s 生成 .config\n' "${profile#"$npc_home"/}"
