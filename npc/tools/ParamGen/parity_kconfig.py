def schema_parameter_semantics(entry: Dict[str, Any]) -> Dict[str, Any]:
    result = {key: entry.get(key) for key in SCHEMA_PARAMETER_KEYS}
    result["defaults"] = [
        {key: item.get(key) for key in ("value", "condition", "kind")}
        for item in entry.get("defaults", [])
    ]
    result["range"] = [
        {key: item.get(key) for key in ("min", "max", "condition")}
        for item in entry.get("range", [])
    ]
    result["selects"] = [
        {key: item.get(key) for key in ("target", "condition")}
        for item in entry.get("selects", [])
    ]
    result["implies"] = [
        {key: item.get(key) for key in ("target", "condition")}
        for item in entry.get("implies", [])
    ]
    return result


def schema_choice_semantics(entry: Dict[str, Any]) -> Dict[str, Any]:
    result = {key: entry.get(key) for key in SCHEMA_CHOICE_KEYS}
    result["defaults"] = [
        {key: item.get(key) for key in ("value", "condition")}
        for item in entry.get("defaults", [])
    ]
    return result


def check_schema_migration(
    schema_path: Path,
    summary_path: Path,
    npc_dir: Path,
    tmp: Path,
) -> Dict[str, Any]:
    """Parse the switched npc/Kconfig with gen_schema and compare semantics.

    schema.json is now the authority, so regenerating it from Kconfig is a
    migration check, not a source of truth.  File/order/tier metadata and the
    association order of ``and`` expressions are expected to differ after the
    switch; symbol types, names, prompts, help, dependencies, defaults and
    ranges must not.
    """
    out = tmp / "schema-migration.json"
    summary = tmp / "schema-migration-summary.json"
    run_checked(
        [
            sys.executable,
            str(HERE / "gen_schema.py"),
            "--kconfig",
            str(npc_dir / "Kconfig"),
            "--out",
            str(out),
            "--summary",
            str(summary),
        ]
    )
    original = p.load_schema(schema_path)
    migrated = p.read_json(out)
    original_params = {
        entry["name"]: schema_parameter_semantics(entry)
        for entry in original.get("parameters", [])
    }
    migrated_params = {
        entry["name"]: schema_parameter_semantics(entry)
        for entry in migrated.get("parameters", [])
    }
    original_choices = {
        entry["id"]: schema_choice_semantics(entry)
        for entry in original.get("choices", [])
    }
    migrated_choices = {
        entry["id"]: schema_choice_semantics(entry)
        for entry in migrated.get("choices", [])
    }
    differences: List[Dict[str, Any]] = []
    for name in sorted(set(original_params) | set(migrated_params)):
        if original_params.get(name) != migrated_params.get(name):
            differences.append(
                {
                    "kind": "parameter",
                    "name": name,
                    "current": original_params.get(name),
                    "migrated": migrated_params.get(name),
                }
            )
    for choice_id in sorted(set(original_choices) | set(migrated_choices)):
        if original_choices.get(choice_id) != migrated_choices.get(choice_id):
            differences.append(
                {
                    "kind": "choice",
                    "name": choice_id,
                    "current": original_choices.get(choice_id),
                    "migrated": migrated_choices.get(choice_id),
                }
            )
    return {
        "parse_ok": True,
        "semantic_equal": not differences,
        "differences": differences[:50],
        "difference_count": len(differences),
        "parameter_count": len(migrated_params),
        "choice_count": len(migrated_choices),
        "menu_count": len(migrated.get("menus", [])),
        "schema_sha256": p.schema_bundle_sha256(schema_path),
        "regenerated_schema_sha256": sha256_file(out),
        "regenerated_summary_sha256": sha256_file(summary),
    }


def check_generator_determinism(
    schema_path: Path, generated_root: Path, tmp: Path
) -> Dict[str, Any]:
    first = tmp / "gen-a"
    second = tmp / "gen-b"
    for target in (first, second):
        run_checked(
            [
                sys.executable,
                str(HERE / "gen_kconfig.py"),
                "--schema",
                str(schema_path),
                "--out",
                str(target / "Kconfig"),
            ]
        )
    first_map = file_map(first)
    second_map = file_map(second)
    checked_map = file_map(generated_root)
    changed = sorted(
        path
        for path in set(first_map) | set(second_map)
        if first_map.get(path) != second_map.get(path)
    )
    expected = set(first_map)
    checked_changed = sorted(
        path
        for path in expected & set(checked_map)
        if first_map[path] != checked_map[path]
    )
    checked_missing = sorted(expected - set(checked_map))
    checked_extra = sorted(set(checked_map) - expected)
    return {
        "byte_identical": not changed,
        "non_identical_files": changed,
        "checked_in_matches_fresh": not checked_changed and not checked_missing,
        "checked_in_differences": checked_changed,
        "checked_in_missing": checked_missing,
        "checked_in_extra_ignored": checked_extra,
        "file_count": len(first_map),
        "file_sha256": {
            path: hashlib.sha256(data).hexdigest()
            for path, data in sorted(first_map.items())
        },
    }


