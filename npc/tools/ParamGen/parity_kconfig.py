def normalize_expr(
    expr: Any,
    kconf: Any,
    choice_ids: Dict[int, str],
    *,
    _depth: int = 0,
) -> Any:
    if _depth > 200:
        return ("depth-limit", kconfiglib.expr_str(expr))
    if isinstance(expr, kconfiglib.Symbol):
        if expr.is_constant:
            return ("const", expr.name)
        return ("sym", expr.name)
    if isinstance(expr, kconfiglib.Choice):
        return ("choice", choice_ids.get(id(expr), expr.name or "<anonymous>"))
    if not isinstance(expr, tuple):
        return ("raw", str(expr))
    op = expr[0]
    if op is kconfiglib.NOT and len(expr) == 2:
        child = normalize_expr(expr[1], kconf, choice_ids, _depth=_depth + 1)
        if child == ("const", "y"):
            return ("const", "n")
        if child == ("const", "n"):
            return ("const", "y")
        if isinstance(child, tuple) and child and child[0] == "not":
            return child[1]
        return ("not", child)
    if op in (kconfiglib.AND, kconfiglib.OR) and len(expr) == 3:
        flattened: List[Any] = []
        identity = ("const", "y") if op is kconfiglib.AND else ("const", "n")
        absorbing = ("const", "n") if op is kconfiglib.AND else ("const", "y")

        def walk(node: Any) -> None:
            if isinstance(node, tuple) and node and node[0] is op:
                walk(node[1])
                walk(node[2])
            else:
                flattened.append(
                    normalize_expr(node, kconf, choice_ids, _depth=_depth + 1)
                )

        walk(expr)
        if absorbing in flattened:
            return absorbing
        unique = sorted(
            {item for item in flattened if item != identity},
            key=repr,
        )
        if not unique:
            return identity
        if len(unique) == 1:
            return unique[0]
        return ("and" if op is kconfiglib.AND else "or", tuple(unique))
    if op in (
        kconfiglib.EQUAL,
        kconfiglib.UNEQUAL,
        kconfiglib.LESS,
        kconfiglib.LESS_EQUAL,
        kconfiglib.GREATER,
        kconfiglib.GREATER_EQUAL,
    ) and len(expr) == 3:
        left = normalize_expr(expr[1], kconf, choice_ids, _depth=_depth + 1)
        right = normalize_expr(expr[2], kconf, choice_ids, _depth=_depth + 1)
        names = {
            kconfiglib.EQUAL: "eq",
            kconfiglib.UNEQUAL: "ne",
            kconfiglib.LESS: "lt",
            kconfiglib.LESS_EQUAL: "lte",
            kconfiglib.GREATER: "gt",
            kconfiglib.GREATER_EQUAL: "gte",
        }
        if op in (kconfiglib.EQUAL, kconfiglib.UNEQUAL):
            left, right = sorted((left, right), key=repr)
        return (names[op], left, right)
    return ("raw", kconfiglib.expr_str(expr))


def norm_value(value: Any) -> Any:
    if isinstance(value, kconfiglib.Symbol):
        if value.is_constant:
            return ("const", value.name)
        return ("sym", value.name)
    return ("raw", str(value))


def describe(value: Any) -> Any:
    """Make normalized tuples JSON-serializable/lisible."""
    if isinstance(value, tuple):
        return [describe(item) for item in value]
    return value


