#!/usr/bin/env python3
"""Verify the switched schema -> Kconfig tree and the 20 defconfig baselines.

The verification has four independent layers:

1. Schema migration: parse the switched ``npc/Kconfig`` with ``gen_schema.py``
   and compare semantic symbol/choice fields with the authoritative
   ``schema.json``.  File/order/tier metadata and ``and`` associativity are
   intentionally ignored because schema.json is the source of truth.
2. Kconfig generation determinism: run ``gen_kconfig.py`` twice and compare
   every generated byte, including the checked-in copy.
3. Symbol/choice/menu parity: parse the entry Kconfig and generated tree with
   Kconfiglib and compare symbol types, prompts, help, dependencies, defaults,
   ranges, selects/implies, choice membership, menu paths and default values.
4. Configuration parity: run all 20 defconfigs through the real ``c_conf``
   binary in isolated /tmp workdirs, generate typed JSON with
   ``npc_config_gen``, and compare effective hashes plus raw ``.config``
   values against the recorded baseline report.
5. Legacy coupling audit: fail if any tracked build/source file still
   references the deleted ``npc/kconfig/Kconfig.*`` tree, or if any of those
   files is still tracked.

Usage:
    python3 npc/tools/ParamGen/parity_kconfig.py
    python3 npc/tools/ParamGen/parity_kconfig.py --workdir /tmp/opencode/parity

The command exits non-zero if any required parity check fails.  Reports are
written even on failure so the concrete differences are available.
"""

