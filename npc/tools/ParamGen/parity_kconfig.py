def compare_symbols(
    left: Any, right: Any, left_choices: Dict[int, str], right_choices: Dict[int, str]
) -> Dict[str, Any]:
    syms_left = {sym.name: sym for sym in left.unique_defined_syms}
    syms_right = {sym.name: sym for sym in right.unique_defined_syms}
    missing = sorted(set(syms_left) - set(syms_right))
    extra = sorted(set(syms_right) - set(syms_left))
    differences: List[Dict[str, Any]] = []

    def add_diff(name: str, field: str, before: Any, after: Any) -> None:
        differences.append(
            {
                "symbol": name,
                "field": field,
                "current": describe(before),
                "generated": describe(after),
            }
        )

    for name in sorted(set(syms_left) & set(syms_right)):
        a = syms_left[name]
        b = syms_right[name]
        node_a = next((node for node in a.nodes if node.prompt), a.nodes[0])
        node_b = next((node for node in b.nodes if node.prompt), b.nodes[0])
        if a.orig_type != b.orig_type:
            add_diff(name, "type", a.orig_type, b.orig_type)
        prompt_a = node_a.prompt[0] if node_a.prompt else None
        prompt_b = node_b.prompt[0] if node_b.prompt else None
        if prompt_a != prompt_b:
            add_diff(name, "prompt", prompt_a, prompt_b)
        help_a = getattr(node_a, "help", None)
        help_b = getattr(node_b, "help", None)
        if help_a != help_b:
            add_diff(name, "help", help_a, help_b)
        dep_a = normalize_expr(node_a.dep, left, left_choices)
        dep_b = normalize_expr(node_b.dep, right, right_choices)
        if dep_a != dep_b:
            add_diff(name, "depends_on", dep_a, dep_b)
        cond_a = (
            normalize_expr(node_a.prompt[1], left, left_choices)
            if node_a.prompt
            else None
        )
        cond_b = (
            normalize_expr(node_b.prompt[1], right, right_choices)
            if node_b.prompt
            else None
        )
        if cond_a != cond_b:
            add_diff(name, "prompt_condition", cond_a, cond_b)
        defaults_a = [
            (norm_value(value), normalize_expr(cond, left, left_choices))
            for value, cond in a.defaults
        ]
        defaults_b = [
            (norm_value(value), normalize_expr(cond, right, right_choices))
            for value, cond in b.defaults
        ]
        if defaults_a != defaults_b:
            add_diff(name, "defaults", defaults_a, defaults_b)
        ranges_a = [
            (
                norm_value(low),
                norm_value(high),
                normalize_expr(cond, left, left_choices),
            )
            for low, high, cond in a.ranges
        ]
        ranges_b = [
            (
                norm_value(low),
                norm_value(high),
                normalize_expr(cond, right, right_choices),
            )
            for low, high, cond in b.ranges
        ]
        if ranges_a != ranges_b:
            add_diff(name, "ranges", ranges_a, ranges_b)
        selects_a = [
            (target.name, normalize_expr(cond, left, left_choices))
            for target, cond in a.selects
        ]
        selects_b = [
            (target.name, normalize_expr(cond, right, right_choices))
            for target, cond in b.selects
        ]
        if selects_a != selects_b:
            add_diff(name, "selects", selects_a, selects_b)
        implies_a = [
            (target.name, normalize_expr(cond, left, left_choices))
            for target, cond in a.implies
        ]
        implies_b = [
            (target.name, normalize_expr(cond, right, right_choices))
            for target, cond in b.implies
        ]
        if implies_a != implies_b:
            add_diff(name, "implies", implies_a, implies_b)
        choice_a = (
            left_choices.get(id(a.choice)) if a.choice is not None else None
        )
        choice_b = (
            right_choices.get(id(b.choice)) if b.choice is not None else None
        )
        if choice_a != choice_b:
            add_diff(name, "choice_group", choice_a, choice_b)
        if bool(getattr(a, "visibility", 0)) != bool(getattr(b, "visibility", 0)):
            add_diff(
                name,
                "visibility",
                bool(getattr(a, "visibility", 0)),
                bool(getattr(b, "visibility", 0)),
            )
        if a.str_value != b.str_value:
            add_diff(name, "default_value", a.str_value, b.str_value)
        if bool(node_a.is_menuconfig) != bool(node_b.is_menuconfig):
            add_diff(name, "is_menuconfig", node_a.is_menuconfig, node_b.is_menuconfig)

    return {
        "count": len(syms_left),
        "missing": missing,
        "extra": extra,
        "differences": differences,
    }


def compare_choices(
    left: Any, right: Any, left_choices: Dict[int, str], right_choices: Dict[int, str]
) -> Dict[str, Any]:
    by_id_left = {left_choices[id(choice)]: choice for choice in left.unique_choices}
    by_id_right = {right_choices[id(choice)]: choice for choice in right.unique_choices}
    missing = sorted(set(by_id_left) - set(by_id_right))
    extra = sorted(set(by_id_right) - set(by_id_left))
    differences: List[Dict[str, Any]] = []

    def add_diff(choice_id: str, field: str, before: Any, after: Any) -> None:
        differences.append(
            {
                "choice": choice_id,
                "field": field,
                "current": describe(before),
                "generated": describe(after),
            }
        )

    for choice_id in sorted(set(by_id_left) & set(by_id_right)):
        a = by_id_left[choice_id]
        b = by_id_right[choice_id]
        node_a = next((node for node in a.nodes if node.prompt), a.nodes[0])
        node_b = next((node for node in b.nodes if node.prompt), b.nodes[0])
        if a.name != b.name:
            add_diff(choice_id, "name", a.name, b.name)
        if a.orig_type != b.orig_type:
            add_diff(choice_id, "type", a.orig_type, b.orig_type)
        prompt_a = node_a.prompt[0] if node_a.prompt else None
        prompt_b = node_b.prompt[0] if node_b.prompt else None
        if prompt_a != prompt_b:
            add_diff(choice_id, "prompt", prompt_a, prompt_b)
        if getattr(node_a, "help", None) != getattr(node_b, "help", None):
            add_diff(
                choice_id,
                "help",
                getattr(node_a, "help", None),
                getattr(node_b, "help", None),
            )
        dep_a = normalize_expr(node_a.dep, left, left_choices)
        dep_b = normalize_expr(node_b.dep, right, right_choices)
        if dep_a != dep_b:
            add_diff(choice_id, "depends_on", dep_a, dep_b)
        cond_a = (
            normalize_expr(node_a.prompt[1], left, left_choices)
            if node_a.prompt
            else None
        )
        cond_b = (
            normalize_expr(node_b.prompt[1], right, right_choices)
            if node_b.prompt
            else None
        )
        if cond_a != cond_b:
            add_diff(choice_id, "prompt_condition", cond_a, cond_b)
        vis_a = normalize_expr(
            getattr(node_a, "visibility", node_a.kconfig.y), left, left_choices
        )
        vis_b = normalize_expr(
            getattr(node_b, "visibility", node_b.kconfig.y), right, right_choices
        )
        if vis_a != vis_b:
            add_diff(choice_id, "visible_if", vis_a, vis_b)
        defaults_a = [
            (norm_value(value), normalize_expr(cond, left, left_choices))
            for value, cond in a.defaults
        ]
        defaults_b = [
            (norm_value(value), normalize_expr(cond, right, right_choices))
            for value, cond in b.defaults
        ]
        if defaults_a != defaults_b:
            add_diff(choice_id, "defaults", defaults_a, defaults_b)
        options_a = [sym.name for sym in a.syms]
        options_b = [sym.name for sym in b.syms]
        if options_a != options_b:
            add_diff(choice_id, "options", options_a, options_b)
        selection_a = a.selection.name if a.selection is not None else None
        selection_b = b.selection.name if b.selection is not None else None
        if selection_a != selection_b:
            add_diff(choice_id, "default_selection", selection_a, selection_b)
        if bool(getattr(a, "visibility", 0)) != bool(getattr(b, "visibility", 0)):
            add_diff(
                choice_id,
                "visibility",
                bool(getattr(a, "visibility", 0)),
                bool(getattr(b, "visibility", 0)),
            )
    return {
        "count": len(by_id_left),
        "missing": missing,
        "extra": extra,
        "differences": differences,
    }


def collect_tree(
    kconf: Any,
    choice_ids: Dict[int, str],
    *,
    mainmenu_override: Optional[str] = None,
) -> Dict[str, Any]:
    mainmenu = (
        mainmenu_override
        if mainmenu_override is not None
        else (kconf.top_node.prompt[0] if kconf.top_node.prompt else None)
    )
    menus: List[Dict[str, Any]] = []
    comments: List[Dict[str, Any]] = []
    symbol_paths: Dict[str, List[str]] = {}
    choice_paths: Dict[str, List[str]] = {}

    def walk(node: Any, path: List[str]) -> None:
        item = node.item
        if item is kconfiglib.MENU:
            prompt = node.prompt[0] if node.prompt else ""
            child_path = path + [prompt]
            menus.append(
                {
                    "path": child_path,
                    "depth": len(child_path),
                    "prompt": prompt,
                    "depends_on": normalize_expr(node.dep, kconf, choice_ids),
                    "visible_if": normalize_expr(
                        getattr(node, "visibility", kconf.y), kconf, choice_ids
                    ),
                }
            )
            child = node.list
            while child:
                walk(child, child_path)
                child = child.next
            return
        if item is kconfiglib.COMMENT:
            comments.append(
                {
                    "path": path,
                    "prompt": node.prompt[0] if node.prompt else "",
                    "depends_on": normalize_expr(node.dep, kconf, choice_ids),
                }
            )
            return
        if isinstance(item, kconfiglib.Choice):
            choice_paths[choice_ids[id(item)]] = path
            return
        if isinstance(item, kconfiglib.Symbol):
            symbol_paths[item.name] = path
            child = node.list
            while child:
                walk(child, path)
                child = child.next

    initial = [mainmenu] if mainmenu else []
    child = kconf.top_node.list
    while child:
        walk(child, initial)
        child = child.next
    return {
        "mainmenu": mainmenu,
        "menus": menus,
        "comments": comments,
        "symbol_paths": symbol_paths,
        "choice_paths": choice_paths,
    }


def compare_trees(left: Dict[str, Any], right: Dict[str, Any]) -> Dict[str, Any]:
    differences: List[Dict[str, Any]] = []
    if left["mainmenu"] != right["mainmenu"]:
        differences.append(
            {
                "field": "mainmenu",
                "current": left["mainmenu"],
                "generated": right["mainmenu"],
            }
        )
    if left["menus"] != right["menus"]:
        limit = min(len(left["menus"]), len(right["menus"]))
        for index in range(limit):
            if left["menus"][index] != right["menus"][index]:
                differences.append(
                    {
                        "field": "menu",
                        "index": index,
                        "current": left["menus"][index],
                        "generated": right["menus"][index],
                    }
                )
        if len(left["menus"]) != len(right["menus"]):
            differences.append(
                {
                    "field": "menu_count",
                    "current": len(left["menus"]),
                    "generated": len(right["menus"]),
                }
            )
    if left["comments"] != right["comments"]:
        differences.append(
            {
                "field": "comments",
                "current": left["comments"],
                "generated": right["comments"],
            }
        )
    for name in sorted(set(left["symbol_paths"]) | set(right["symbol_paths"])):
        a = left["symbol_paths"].get(name, MISSING)
        b = right["symbol_paths"].get(name, MISSING)
        if a != b:
            differences.append(
                {
                    "field": "symbol_menu_path",
                    "symbol": name,
                    "current": None if a is MISSING else a,
                    "generated": None if b is MISSING else b,
                }
            )
    for choice_id in sorted(set(left["choice_paths"]) | set(right["choice_paths"])):
        a = left["choice_paths"].get(choice_id, MISSING)
        b = right["choice_paths"].get(choice_id, MISSING)
        if a != b:
            differences.append(
                {
                    "field": "choice_menu_path",
                    "choice": choice_id,
                    "current": None if a is MISSING else a,
                    "generated": None if b is MISSING else b,
                }
            )
    return {
        "menu_count": len(left["menus"]),
        "comment_count": len(left["comments"]),
        "differences": differences,
    }


