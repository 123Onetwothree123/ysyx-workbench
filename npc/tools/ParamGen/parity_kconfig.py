def generated_kconfig_files(root: Path) -> List[Path]:
    return sorted(
        path
        for path in root.rglob("*")
        if path.is_file()
        and (path.name == "Kconfig" or path.name.endswith(".Kconfig"))
    )


def file_map(root: Path) -> Dict[str, bytes]:
    result: Dict[str, bytes] = {}
    for path in generated_kconfig_files(root):
        result[str(path.relative_to(root))] = path.read_bytes()
    return result


