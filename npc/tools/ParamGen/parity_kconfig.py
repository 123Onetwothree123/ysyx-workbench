def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run_checked(
    command: Sequence[str], *, cwd: Optional[Path] = None
) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(
            list(command),
            cwd=str(cwd) if cwd else None,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
    except subprocess.CalledProcessError as error:
        raise p.ParamError(
            f"command failed ({' '.join(str(part) for part in command)}):\n"
            f"{error.stdout.strip()}\n{error.stderr.strip()}"
        ) from error


def load_kconfig(top: Path, srctree: Path) -> Any:
    """Load a Kconfig tree, starting from an empty configuration."""
    top = top.resolve()
    srctree = srctree.resolve()
    relative = os.path.relpath(top, srctree)
    previous = os.environ.get("srctree")
    os.environ["srctree"] = str(srctree)
    try:
        kconf = kconfiglib.Kconfig(relative, warn=False, warn_to_stderr=False)
        with tempfile.NamedTemporaryFile("w", delete=False) as handle:
            empty = handle.name
        try:
            kconf.load_config(empty)
        finally:
            try:
                os.unlink(empty)
            except OSError:
                pass
    finally:
        if previous is None:
            os.environ.pop("srctree", None)
        else:
            os.environ["srctree"] = previous
    return kconf


