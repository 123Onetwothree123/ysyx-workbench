def prepare_workdir(
    workdir: Path,
    top: Path,
    source_root: Path,
    source_prefix: str = "params/generated",
) -> None:
    """Mirror the paths c_conf resolves relative to its working directory.

    Generated ``source`` statements are relative to ``npc/`` (the srctree),
    not to the generated file's directory.  The workdir therefore exposes the
    top-level Kconfig and the generated root at the same relative path used by
    the repository.
    """
    if workdir.exists():
        shutil.rmtree(workdir)
    (workdir / "include/generated").mkdir(parents=True)
    (workdir / "include/config").mkdir(parents=True)
    (workdir / "Kconfig").symlink_to(top.resolve())
    source_link = workdir / source_prefix
    source_link.parent.mkdir(parents=True, exist_ok=True)
    source_link.symlink_to(source_root.resolve(), target_is_directory=True)


def dotconfig_values(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"^(CONFIG_[A-Za-z0-9_]+)=(.*)$", line)
        if match:
            values[match.group(1)] = match.group(2)
            continue
        match = re.match(r"^# (CONFIG_[A-Za-z0-9_]+) is not set$", line)
        if match:
            values[match.group(1)] = "n"
    return values


def generate_typed(
    workdir: Path,
    top: Path,
    source_root: Path,
    defconfig: Path,
    *,
    conf: Path,
    config_gen: Path,
) -> Dict[str, Any]:
    prepare_workdir(workdir, top, source_root)
    run_checked(
        [str(conf), "-s", f"--defconfig={defconfig.resolve()}", "Kconfig"],
        cwd=workdir,
    )
    run_checked([str(conf), "-s", "--syncconfig", "Kconfig"], cwd=workdir)
    run_checked(
        [
            str(config_gen),
            "--config-json",
            str(workdir / "include/generated/npc_config.json"),
            "--typed-json",
            str(workdir / "typed.json"),
        ],
        cwd=workdir,
    )
    return {
        "typed": p.read_json(workdir / "typed.json"),
        "dotconfig": dotconfig_values(workdir / ".config"),
    }


def recursive_diff(
    before: Any,
    after: Any,
    path: str,
    *,
    limit: int = 200,
    output: Optional[List[Dict[str, Any]]] = None,
) -> List[Dict[str, Any]]:
    if output is None:
        output = []
    if len(output) >= limit:
        return output
    if type(before) is not type(after) and not (
        isinstance(before, (int, float))
        and isinstance(after, (int, float))
        and not isinstance(before, bool)
        and not isinstance(after, bool)
    ):
        output.append({"path": path, "current": before, "generated": after})
        return output
    if isinstance(before, dict) and isinstance(after, dict):
        for key in sorted(set(before) | set(after)):
            if len(output) >= limit:
                break
            if key not in before:
                output.append(
                    {"path": f"{path}.{key}" if path else key, "current": None, "generated": after[key]}
                )
            elif key not in after:
                output.append(
                    {"path": f"{path}.{key}" if path else key, "current": before[key], "generated": None}
                )
            else:
                recursive_diff(
                    before[key],
                    after[key],
                    f"{path}.{key}" if path else key,
                    limit=limit,
                    output=output,
                )
        return output
    if isinstance(before, list) and isinstance(after, list):
        if len(before) != len(after):
            output.append(
                {
                    "path": f"{path}.length",
                    "current": len(before),
                    "generated": len(after),
                }
            )
        for index in range(min(len(before), len(after))):
            if len(output) >= limit:
                break
            recursive_diff(
                before[index],
                after[index],
                f"{path}[{index}]",
                limit=limit,
                output=output,
            )
        return output
    if before != after:
        output.append({"path": path, "current": before, "generated": after})
    return output


def compare_configs(
    current: Dict[str, Any],
    generated: Dict[str, Any],
    schema: Dict[str, Any],
) -> Dict[str, Any]:
    current_doc = p.canonical_document(current["typed"], schema)
    generated_doc = p.canonical_document(generated["typed"], schema)
    hash_match = current_doc["effective_hash"] == generated_doc["effective_hash"]
    canonical_diff = recursive_diff(
        current_doc["canonical"], generated_doc["canonical"], ""
    ) if not hash_match else []
    dot_diff = recursive_diff(
        current["dotconfig"], generated["dotconfig"], ""
    )
    return {
        "current_hash": current_doc["effective_hash"],
        "generated_hash": generated_doc["effective_hash"],
        "hash_match": hash_match,
        "canonical_equal": current_doc["canonical"] == generated_doc["canonical"],
        "canonical_differences": canonical_diff,
        "dotconfig_equal": current["dotconfig"] == generated["dotconfig"],
        "dotconfig_difference_count": len(dot_diff),
        "dotconfig_differences": dot_diff[:50],
    }


def read_recorded_hashes(path: Path) -> Dict[str, str]:
    if not path.exists():
        return {}
    result: Dict[str, str] = {}
    with path.open("r", encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            if row.get("defconfig") and row.get("effective_hash"):
                result[row["defconfig"]] = row["effective_hash"]
    return result


