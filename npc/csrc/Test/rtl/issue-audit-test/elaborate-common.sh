#!/bin/bash
# issue-audit 快照公共配置：所有快照固定为 RV32（无 MMU），
# 与仓库本地 .config（可能是 RV64）解耦。
TEST_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
CFG="$TEST_DIR/../../common/elaborate_config.sh"
BUILD="$TEST_DIR/build"

RV32_CONFIG=(CONFIG_XLEN=32 CONFIG_SOC_XLEN_FOLLOW_CPU=n CONFIG_SOC_XLEN=32
  CONFIG_ADDRESS_WIDTH=32 CONFIG_HAS_MMU=n CONFIG_HAS_TLB=n
  CONFIG_MMU_PTE_FORMAT=riscv32 CONFIG_MMU_PTE_RISCV32=y
  CONFIG_MMU_PTE_RISCV64=n CONFIG_MMU_PTE_SIZE_BYTES=4
  CONFIG_MMU_PTE_PPN_HIGH=31 CONFIG_MMU_LEVELS=2
  CONFIG_RISCV_F=n CONFIG_RISCV_D=n CONFIG_FPU_IMPL=none)
# AXIRAM 审计探针按 0x80000000..0x8003FFFF（256KiB）检查跨窗口拒绝；
# 快照的 RAM 窗口必须与探针一致，不能用生产默认 64MiB。
BASE_CONFIG=(CONFIG_NPC_RAM_SIZE=0x40000
  CONFIG_CACHE_BLOCK_SIZE_LOG2=4 CONFIG_CACHE_INDEX_BITS=5
  CONFIG_ICACHE=y CONFIG_DCACHE=y CONFIG_WBUF_DEPTH=4 CONFIG_CACHE_PADDING=0
  CONFIG_CHIPLINK=n CONFIG_BTB_BITS=4 CONFIG_BTB_WAYS=1
  CONFIG_JAL_BTB_BITS=4 CONFIG_JAL_BTB_WAYS=1 CONFIG_RAS_BITS=4
  CONFIG_RISCV_M=y CONFIG_RISCV_A=n CONFIG_RISCV_C=n
  CONFIG_HAS_S=y CONFIG_HAS_U=y CONFIG_HAS_S_EXTERNAL_IRQ=n
  CONFIG_MUL_IMPL=shift_add CONFIG_MUL_ENCODING=plain CONFIG_MUL_RADIX=4
  CONFIG_MUL_WIDTH=32 CONFIG_MUL_ITER_BITS=1 CONFIG_MUL_PIPELINE=0
  CONFIG_MUL_SPLIT=1 CONFIG_MUL_EARLY_OUT=n
  CONFIG_DIV_IMPL=restoring CONFIG_DIV_RADIX=2 CONFIG_DIV_ITER_BITS=1
  CONFIG_DIV_EARLY_OUT=n
  CONFIG_SDB=y CONFIG_DIFFTEST=y CONFIG_MTRACE=y CONFIG_ITRACE=y
  CONFIG_FTRACE=y CONFIG_IRINGBUF=y CONFIG_PERF_DIC_ARCH_COUNTER=y)

# elaborate <target_dir> [CONFIG_X=... ...]
elaborate() {
  local target=$1
  shift
  "$CFG" "$TEST_DIR" "$target" "$@"
}
