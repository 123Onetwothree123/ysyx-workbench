#!/bin/bash
set -eo pipefail
source "$(dirname "$0")/elaborate-common.sh"
mkdir -p "$BUILD/rtl-gpc32"
elaborate "$BUILD/rtl-gpc32" "${RV32_CONFIG[@]}" "${BASE_CONFIG[@]}" \
  CONFIG_MUL_IMPL=wallace CONFIG_MUL_ENCODING=plain CONFIG_MUL_RADIX=4 CONFIG_MUL_WIDTH=32 \
  CONFIG_MUL_COMPRESSOR_INPUTS=3 CONFIG_MUL_COMPRESSOR_OUTPUTS=2 \
  CONFIG_MUL_COMPRESSOR_OUTPUT_OFFSETS=0,1 \
  CONFIG_MUL_COMPRESSOR_HAS_CIN=n CONFIG_MUL_COMPRESSOR_HAS_COUT=n \
  CONFIG_MUL_COMPRESSOR_ALLOW_REDUNDANT=n \
  CONFIG_MUL_ITER_BITS=1 CONFIG_MUL_PIPELINE=2 CONFIG_MUL_SPLIT=1 CONFIG_MUL_EARLY_OUT=n \
  CONFIG_DIV_IMPL=restoring CONFIG_DIV_RADIX=2 CONFIG_DIV_ITER_BITS=1 CONFIG_DIV_EARLY_OUT=n \
  2>&1 | tail -2
